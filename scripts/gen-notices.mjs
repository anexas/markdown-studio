// Regenerates THIRD-PARTY-NOTICES.md from the dependency graph that actually ships.
//
// JavaScript packages come from package-lock.json (production entries only), which is
// the set Vite bundles. Rust crates come from `cargo metadata` filtered to the Windows
// target, so Android/iOS/wasm crates do not pad the list.
//
// Run with `npm run notices` after changing dependencies.
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const app = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const TARGET = "x86_64-pc-windows-msvc";

// Dual-licence expressions are resolved to the option with the fewest obligations:
// taking Apache-2.0 over MPL-2.0 avoids MPL's source-disclosure requirement.
const PREFERRED = ["Apache-2.0", "MIT", "BSD-3-Clause", "ISC", "BSD-2-Clause", "Unlicense", "MPL-2.0"];

function pickLicence(raw) {
  if (!raw) return "UNKNOWN";
  const options = String(raw)
    .replace(/[()]/g, "")
    .trim()
    .split(/\s+OR\s+/i)
    .map((option) => option.trim());
  for (const preferred of PREFERRED) if (options.includes(preferred)) return preferred;
  return options[0];
}

function licenceFile(dir) {
  for (const name of ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING", "LICENSE-MIT"]) {
    const file = path.join(dir, name);
    if (fs.existsSync(file)) return file;
  }
  return null;
}

function copyrightLines(file) {
  if (!file) return [];
  return fs
    .readFileSync(file, "utf8")
    .split(/\r?\n/)
    .filter((line) => /copyright|\(c\)\s*\d{4}/i.test(line) && line.trim().length > 0)
    .map((line) => line.trim())
    .slice(0, 2);
}

// ---------------------------------------------------------------- JavaScript

const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
const js = [];

for (const [key, entry] of Object.entries(lock.packages ?? {})) {
  if (!key || entry.dev || entry.link) continue;
  const dir = path.join(root, key);
  const manifest = path.join(dir, "package.json");
  if (!fs.existsSync(manifest)) continue;
  const pkg = JSON.parse(fs.readFileSync(manifest, "utf8"));
  if (!pkg.name) continue;
  const file = licenceFile(dir);
  js.push({
    name: pkg.name,
    version: pkg.version ?? entry.version ?? "",
    licence: pickLicence(pkg.license ?? pkg.licenses?.[0]?.type),
    text: file ? fs.readFileSync(file, "utf8").trim() : "",
    copyright: copyrightLines(file),
  });
}
js.sort((a, b) => a.name.localeCompare(b.name));

// ---------------------------------------------------------------------- Rust

let rust = [];
try {
  const meta = JSON.parse(
    execSync(`cargo metadata --format-version 1 --filter-platform ${TARGET} --manifest-path src-tauri/Cargo.toml`, {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 1 << 28,
      stdio: ["ignore", "pipe", "ignore"],
    }),
  );
  rust = meta.packages
    .filter((pkg) => pkg.name !== app.name)
    .map((pkg) => ({ name: pkg.name, version: pkg.version, licence: pickLicence(pkg.license) }))
    .sort((a, b) => a.name.localeCompare(b.name));
} catch {
  rust = [];
}

if (rust.length === 0) {
  // Without cargo on PATH, fall back to the lockfile so the file still names every
  // crate, and say so rather than silently claiming licences that were never read.
  const lockText = fs.readFileSync(path.join(root, "src-tauri/Cargo.lock"), "utf8");
  rust = [...lockText.matchAll(/^name = "(.+)"\nversion = "(.+)"/gm)]
    .map((match) => ({ name: match[1], version: match[2], licence: "see crate" }))
    .filter((crate) => crate.name !== app.name)
    .sort((a, b) => a.name.localeCompare(b.name));
}

const javeScriptFallback = rust.some((crate) => crate.licence === "see crate");

// ------------------------------------------------------------ notice grouping

const byLicence = new Map();
for (const pkg of js) {
  const group = byLicence.get(pkg.licence) ?? { packages: [], text: "", copyrights: new Set() };
  group.packages.push(pkg);
  if (pkg.text.length > group.text.length) group.text = pkg.text;
  for (const line of pkg.copyright) group.copyrights.add(line);
  byLicence.set(pkg.licence, group);
}

// ------------------------------------------------------------------- output

const out = [];
out.push("# Third-party notices", "");
out.push(`Markdown Studio ${app.version} is built on third-party software. This file lists the`);
out.push("components distributed with it and reproduces the licence texts those licences require.", "");
out.push(`Generated by \`npm run notices\` from package-lock.json and \`cargo metadata\`.`);
out.push("");

out.push("## JavaScript bundled into the interface", "");
out.push(`${js.length} packages.`, "", "| Component | Version | Licence |", "| --- | --- | --- |");
for (const pkg of js) out.push(`| ${pkg.name} | ${pkg.version} | ${pkg.licence} |`);
out.push("");

out.push("## Rust crates linked into the executable", "");
out.push(`${rust.length} crates resolved for ${TARGET}. Crate sources are available from`);
out.push("crates.io, and each crate's repository is linked from its crates.io page.", "");
if (javeScriptFallback) {
  out.push("> Note: `cargo metadata` was unavailable when this file was generated, so the licence");
  out.push("> column fell back to the lockfile. Re-run `npm run notices` with Rust on PATH.");
  out.push("");
}
out.push("| Crate | Version | Licence |", "| --- | --- | --- |");
for (const crate of rust) out.push(`| ${crate.name} | ${crate.version} | ${crate.licence} |`);
out.push("");

out.push("## Licence texts", "");
for (const licence of [...byLicence.keys()].sort()) {
  const group = byLicence.get(licence);
  const named = group.packages.sort((a, b) => a.name.localeCompare(b.name));
  out.push(`### ${licence}`, "");
  out.push(
    `Applies to ${named.length} package${named.length === 1 ? "" : "s"}: ${named
      .map((pkg) => `${pkg.name} ${pkg.version}`)
      .join(", ")}.`,
    "",
  );
  if (group.copyrights.size > 0) out.push([...group.copyrights].sort().join("\n"), "");
  if (group.text) out.push("```", group.text, "```", "");
  else out.push("_No licence file was published with these packages._", "");
}

const target = path.join(root, "THIRD-PARTY-NOTICES.md");
fs.writeFileSync(target, out.join("\n"), "utf8");

console.log(`javascript packages : ${js.length}`);
console.log(`rust crates         : ${rust.length}`);
console.log(`licence sections    : ${byLicence.size} (${[...byLicence.keys()].sort().join(", ")})`);
console.log(`written             : ${path.relative(root, target)} (${(fs.statSync(target).size / 1024).toFixed(1)} KB)`);
